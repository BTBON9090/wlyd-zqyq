/** 热门需求：报价数 + 发布时间新鲜度 */
export function getHotDemands(limit = 8, today = new Date("2026-09-07")) {
  const score = (d: DemandPost) => {
    const age = Math.max(0, Math.floor((today.getTime() - new Date(d.publishedAt).getTime()) / 86400000));
    const recency = Math.max(0, 40 - age);
    return d.quotes * 3 + recency;
  };
  return [...demandPosts].sort((a, b) => score(b) - score(a)).slice(0, limit);
}
